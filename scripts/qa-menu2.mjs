import puppeteer from 'puppeteer-core';
const CHROME='/Applications/Google Chrome.app/Contents/MacOS/Google Chrome';
const sleep=(ms)=>new Promise(r=>setTimeout(r,ms));
const browser=await puppeteer.launch({executablePath:CHROME,headless:'new',args:['--no-sandbox','--disable-gpu','--hide-scrollbars']});
const page=await browser.newPage();
await page.setViewport({width:390,height:844,deviceScaleFactor:2,isMobile:true,hasTouch:true});
await page.evaluateOnNewDocument(()=>{try{sessionStorage.setItem('rr-visited','1');}catch{}});
await page.goto('http://localhost:3000/',{waitUntil:'networkidle2'});
await sleep(900);
await page.click('button[aria-label="Open menu"]');
await sleep(600);
const label = await page.evaluate(()=>{
  const b=document.querySelector('button[aria-label="Show Elevators links"]');
  if(!b) return 'missing';
  b.click();
  return 'clicked';
});
console.log(label);
await sleep(700);
await page.screenshot({path:'/tmp/rr-menu-sub-mobile.png'});
console.log(await page.evaluate(()=>Array.from(document.querySelectorAll('button[aria-expanded]')).map(b=>[b.getAttribute('aria-label'),b.getAttribute('aria-expanded')]).filter(x=>x[0])));
await browser.close();
