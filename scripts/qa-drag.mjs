import puppeteer from 'puppeteer-core';
const CHROME='/Applications/Google Chrome.app/Contents/MacOS/Google Chrome';
const sleep=(ms)=>new Promise(r=>setTimeout(r,ms));
const browser=await puppeteer.launch({executablePath:CHROME,headless:'new',args:['--no-sandbox','--disable-gpu','--hide-scrollbars']});
const page=await browser.newPage();
await page.setViewport({width:1440,height:900});
await page.evaluateOnNewDocument(()=>{try{sessionStorage.setItem('rr-visited','1');}catch{}});
await page.goto('http://localhost:3000/interiors',{waitUntil:'networkidle2'});
await sleep(800);
await page.evaluate(()=>window.scrollTo(0,900));
await sleep(1800);
const box = await page.evaluate(()=>{const el=document.querySelector('[role="application"]'); const r=el.getBoundingClientRect(); return {x:r.x+r.width/2,y:r.y+r.height/2};});
console.log(box);
const drag=async(dx)=>{
  await page.mouse.move(box.x, box.y);
  await page.mouse.down();
  await page.mouse.move(box.x+dx, box.y, {steps:12});
  await page.mouse.up();
  await sleep(1400);
  await page.screenshot({path:`/tmp/rr-drag-${dx}.png`, clip:{x:58,y:318,width:958,height:510}});
};
await drag(250);
await drag(250);
await drag(250);
await browser.close();
