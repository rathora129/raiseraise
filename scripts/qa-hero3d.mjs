import puppeteer from 'puppeteer-core';
const CHROME='/Applications/Google Chrome.app/Contents/MacOS/Google Chrome';
const sleep=(ms)=>new Promise(r=>setTimeout(r,ms));
const browser=await puppeteer.launch({executablePath:CHROME,headless:'new',args:['--no-sandbox','--hide-scrollbars','--enable-unsafe-swiftshader','--use-angle=swiftshader']});
const page=await browser.newPage();
await page.setViewport({width:1440,height:900,deviceScaleFactor:1});
const msgs=[];
page.on('console',m=>{if(['error','warning'].includes(m.type()))msgs.push(m.type()+': '+m.text())});
page.on('pageerror',e=>msgs.push('pageerror: '+e.message));
await page.evaluateOnNewDocument(()=>{try{sessionStorage.setItem('rr-visited','1');}catch{}});
await page.goto('http://localhost:3000/',{waitUntil:'networkidle2'});
await sleep(3500);
console.log('canvas', await page.evaluate(()=>!!document.querySelector('main canvas')));
await page.screenshot({path:'/tmp/rr-hero-webgl.png'});
await page.evaluate(()=>window.scrollTo(0,420));
await sleep(1400);
await page.screenshot({path:'/tmp/rr-hero-webgl-mid.png'});
console.log(msgs.length?msgs.join('\n'):'console clean');
await browser.close();
